#!/usr/bin/env node
/*
 * Extracts the approved logo artwork from the official brand pack SVGs
 * (brand/official/SVG) into src/components/brand/logo-paths.ts, so the
 * website, icons, share image and video frames all draw the exact supplied
 * outlines. Run again only if the brand pack is updated:
 *
 *   node brand/tools/build-logo-paths.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const svgDir = resolve(root, "brand/official/SVG");
const out = resolve(root, "src/components/brand/logo-paths.ts");

function parse(file) {
  const svg = readFileSync(resolve(svgDir, file), "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  const groups = [];
  for (const g of svg.matchAll(/<g fill="([^"]+)">(.*?)<\/g>/gs)) {
    const paths = [];
    for (const p of g[2].matchAll(/<path d="([^"]+)"(?: transform="translate\(([^,]+),([^)]+)\)")?/g)) {
      paths.push({ d: p[1].trim(), tx: Number(p[2] ?? 0), ty: Number(p[3] ?? 0) });
    }
    groups.push({ fill: g[1], paths });
  }
  return { viewBox, groups };
}

const primary = parse("Brand_It_China_Primary.svg");
const wordmark = parse("Brand_It_China_Wordmark_Black.svg");
const seal = parse("Brand_It_China_Seal_Red.svg");

const ink = primary.groups.find((g) => g.fill === "#202020");
const sealBg = primary.groups.find((g) => g.fill === "#E63329");
const sealGlyph = primary.groups.find((g) => g.fill === "#FFFFFF");
if (!ink || !sealBg || !sealGlyph) throw new Error("Unexpected Primary.svg structure");

const fmt = (paths) => JSON.stringify(paths.map((p) => ({ d: p.d, tx: p.tx, ty: p.ty })), null, 0);

writeFileSync(
  out,
  `// Generated by brand/tools/build-logo-paths.mjs from the official brand pack
// (brand/official/SVG). These are the approved outlines. Do not hand edit.

/** Full lockup artboard: Brand_It_China_Primary.svg */
export const LOGO_VIEWBOX = "${primary.viewBox.join(" ")}";
export const LOGO_WIDTH = ${primary.viewBox[2]};
export const LOGO_HEIGHT = ${primary.viewBox[3]};

/** Wordmark only artboard: Brand_It_China_Wordmark_Black.svg */
export const WORDMARK_WIDTH = ${wordmark.viewBox[2]};
export const WORDMARK_HEIGHT = ${wordmark.viewBox[3]};

/** The seal's bounds inside the lockup artboard (Brand_It_China_Seal_Red.svg viewBox). */
export const SEAL_BOUNDS = { x: ${seal.viewBox[0]}, y: ${seal.viewBox[1]}, width: ${seal.viewBox[2]}, height: ${seal.viewBox[3]} };

export type ArtPath = { d: string; tx: number; ty: number };

/** Letters and the long t stroke, in lockup coordinates. */
export const WORDMARK_PATHS: ArtPath[] = ${fmt(ink.paths)};

/** The seal background, in lockup coordinates. */
export const SEAL_BACKGROUND_PATHS: ArtPath[] = ${fmt(sealBg.paths)};

/** The seal character 创 ("create"), in lockup coordinates. */
export const SEAL_GLYPH_PATHS: ArtPath[] = ${fmt(sealGlyph.paths)};
`
);
console.log("wrote", out, { wordmarkPaths: ink.paths.length, sealBg: sealBg.paths.length, glyph: sealGlyph.paths.length, seal: seal.viewBox });
