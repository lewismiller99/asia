#!/usr/bin/env node
/*
 * Regenerates src/components/brand/logo-paths.ts from the brand fonts.
 * Only needed if the wordmark typography changes or an official vector is
 * being matched. Requires opentype.js (installed as a dev dependency).
 *
 *   node brand/tools/build-logo-paths.js
 */
const ot = require("opentype.js");
const fs = require("node:fs");
const path = require("node:path");

const fonts = path.resolve(__dirname, "../fonts");
const out = path.resolve(__dirname, "../../src/components/brand/logo-paths.ts");

function outline(file, text, size, tracking) {
  const font = ot.loadSync(path.join(fonts, file));
  const glyphs = font.stringToGlyphs(text);
  const scale = size / font.unitsPerEm;
  let x = 0;
  const parts = [];
  glyphs.forEach((glyph, i) => {
    parts.push(glyph.getPath(x, 0, size).toPathData(2));
    let advance = glyph.advanceWidth * scale;
    if (i < glyphs.length - 1) advance += font.getKerningValue(glyph, glyphs[i + 1]) * scale;
    x += advance + tracking * size;
  });
  return { d: parts.join(" "), width: x - tracking * size };
}

const brandit = outline("archivo-800.woff", "brand it", 100, -0.03);
const china = outline("archivo-500-exp.woff", "china", 100, 0.18);

fs.writeFileSync(
  out,
  `// Generated by brand/tools/build-logo-paths.js from the approved wordmark
// typography (Archivo ExtraBold for "brand it", Archivo Expanded Medium for
// "china"). The text is converted to outlines so the mark renders identically
// on every device regardless of font loading. Do not hand edit.

export const BRANDIT_PATH = ${JSON.stringify(brandit.d)};
export const BRANDIT_WIDTH = ${brandit.width};

export const CHINA_PATH = ${JSON.stringify(china.d)};
export const CHINA_WIDTH = ${china.width};
`
);
console.log("wrote", out);
