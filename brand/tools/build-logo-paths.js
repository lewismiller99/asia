#!/usr/bin/env node
/*
 * Regenerates src/components/brand/logo-paths.ts from the brand fonts.
 *
 * The approved mark sets "brand it" and "china" in League Spartan Black and
 * stamps 创 ("create") from ZCOOL XiaoWei inside the red seal. Both faces
 * are SIL Open Font Licence. The text is converted to outlines, with the
 * metrics the lockup geometry depends on, so the mark never relies on font
 * loading. Requires opentype.js (a dev dependency).
 *
 *   node brand/tools/build-logo-paths.js
 */
const ot = require("opentype.js");
const fs = require("node:fs");
const path = require("node:path");

const fonts = path.resolve(__dirname, "../fonts");
const out = path.resolve(__dirname, "../../src/components/brand/logo-paths.ts");

const SIZE = 100; // wordmark font size in logo units
const TRACKING = -0.02; // em

const spartan = ot.loadSync(path.join(fonts, "league-spartan-900.woff"));
const zcool = ot.loadSync(path.join(fonts, "zcool-xiaowei-chuang-subset.woff"));
const k = SIZE / spartan.unitsPerEm;

function outline(font, text, size, tracking) {
  const glyphs = font.stringToGlyphs(text);
  const scale = size / font.unitsPerEm;
  let x = 0;
  const parts = [];
  let lastGlyphRight = 0;
  glyphs.forEach((glyph, i) => {
    parts.push(glyph.getPath(x, 0, size).toPathData(2));
    lastGlyphRight = x + glyph.getBoundingBox().x2 * scale;
    let advance = glyph.advanceWidth * scale;
    if (i < glyphs.length - 1) advance += font.getKerningValue(glyph, glyphs[i + 1]) * scale;
    x += advance + tracking * size;
  });
  return { d: parts.join(" "), inkRight: lastGlyphRight, inkLeft: glyphs[0].getBoundingBox().x1 * scale };
}

// The crossbar of "t": the horizontal bar at the glyph's right edge. Scan
// the outline for the y values of points sitting on that edge.
function crossbar() {
  const t = spartan.charToGlyph("t");
  const bb = t.getBoundingBox();
  // Points within a quarter stem of the right edge, and no lower than one
  // and a half stems below the x-height, belong to the bar's end (the foot
  // of the "t" also reaches the right edge and must be excluded).
  const stemUnits = spartan.charToGlyph("l").getBoundingBox().x2 - spartan.charToGlyph("l").getBoundingBox().x1;
  const edge = bb.x2 - stemUnits * 0.25;
  const floor = spartan.tables.os2.sxHeight - stemUnits * 1.5;
  const ys = t.path.commands.filter((c) => c.x !== undefined && c.x >= edge && c.y >= floor).map((c) => c.y);
  const top = Math.max(...ys) * k; // font units are y-up
  const bottom = Math.min(...ys) * k;
  return { top: -top, bottom: -bottom }; // SVG y-down, baseline at 0
}

const brandit = outline(spartan, "brand it", SIZE, TRACKING);
const china = outline(spartan, "china", SIZE, TRACKING);
const bar = crossbar();
const ascender = spartan.charToGlyph("b").getBoundingBox().y2 * k;
const stem = (spartan.charToGlyph("l").getBoundingBox().x2 - spartan.charToGlyph("l").getBoundingBox().x1) * k;

const sealGlyph = zcool.charToGlyph("创");
const sealBox = sealGlyph.getBoundingBox();
const sealPath = sealGlyph.getPath(0, 0, 100).toPathData(2); // 100 unit em, baseline 0
const zs = 100 / zcool.unitsPerEm;

fs.writeFileSync(
  out,
  `// Generated by brand/tools/build-logo-paths.js. Do not hand edit.
//
// "brand it" and "china" are League Spartan Black outlines set at a font
// size of 100 with the baseline at y = 0 and ${TRACKING}em tracking. The seal
// glyph is 创 from ZCOOL XiaoWei at a 100 unit em, baseline at y = 0.

export const BRANDIT_PATH = ${JSON.stringify(brandit.d)};
export const BRANDIT_INK_LEFT = ${brandit.inkLeft.toFixed(2)};
export const BRANDIT_INK_RIGHT = ${brandit.inkRight.toFixed(2)};

export const CHINA_PATH = ${JSON.stringify(china.d)};
export const CHINA_INK_LEFT = ${china.inkLeft.toFixed(2)};
export const CHINA_INK_RIGHT = ${china.inkRight.toFixed(2)};

/** Ascender height of "b" in logo units. */
export const ASCENDER = ${ascender.toFixed(2)};
/** Vertical stem weight in logo units. */
export const STEM = ${stem.toFixed(2)};
/** The "t" crossbar, which the rule continues: y values with the baseline at 0, y down. */
export const CROSSBAR_TOP = ${bar.top.toFixed(2)};
export const CROSSBAR_BOTTOM = ${bar.bottom.toFixed(2)};

export const SEAL_GLYPH_PATH = ${JSON.stringify(sealPath)};
/** Bounding box of the seal glyph in its 100 unit em (y down, baseline 0). */
export const SEAL_GLYPH_BOX = { x1: ${(sealBox.x1 * zs).toFixed(2)}, y1: ${(-sealBox.y2 * zs).toFixed(2)}, x2: ${(sealBox.x2 * zs).toFixed(2)}, y2: ${(-sealBox.y1 * zs).toFixed(2)} };
`
);
console.log("wrote", out, { ascender, stem, bar, inkRight: brandit.inkRight, chinaRight: china.inkRight });
